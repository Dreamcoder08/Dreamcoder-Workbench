"""Every Dark colour file is generated, or carries only current Dark tokens.

Spec: odd/tasks/dreamcoder-dark-coherence.md, T4 (S1); mirrors
tests/test_light_color_files.py (Light coherence T8, L16).

A tracked Dark colour file is either written by the sync (so it can never drift
from ``tokens.json``) or, when it is not, every hex literal in it must be an
exact current ``modes.dark`` value. Exceptions need a written reason.
"""

from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest
from test_light_color_files import (
    HEX,
    NOT_COLOUR_FILES,
    ROOT,
    TOKENS,
    _generated_by_sync,
    _resolved,
    _stale,
    _tracked,
)

from dreamcoder_theme import sync
from dreamcoder_theme.palette import load_variants
from dreamcoder_theme.palette_tokens import VARIANTS
from dreamcoder_theme.renderers_extra_gtk_qt import qt6ct_content
from dreamcoder_theme.renderers_mode_files import (
    MODE_FILES,
    ZELLIJ_CONFIGS,
    tmux_ukiyo_content,
    zellij_config_content,
)

DARK_FILES = MODE_FILES["dark"]
ZELLIJ_DARK_CONFIG = ZELLIJ_CONFIGS["dark"]

# `dark` as a whole word in the file name (`darkroom`, `darker` do not count).
DARK_NAME = re.compile(r"(?<![a-z])dark(?![a-z])", re.IGNORECASE)
# Dark-only colour files whose name does not say so.
DARK_ONLY_BY_CONTENT = ("DreamcoderNushell/README.md",)
# Written reasons are mandatory; an entry that is generated or untracked fails.
ALLOWLIST: dict[str, str] = {
    "DreamcoderThemes/dreamcoder/dreamcoder-dark.css": (
        "generated by scripts/generate-dark-css.py, not by the sync; it also prints the "
        "modes.dark.aliases values (brand, border_*, text_muted, error_requested); its drift "
        "gate is pinned below by test_allowlisted_dark_css_equals_its_generator"
    ),
    "DreamcoderThemes/dreamcoder/qt6ct-dark.conf": (
        "generated by the toolkit pass, not the repo-only snippets; qt6ct writes ARGB (#ffRRGGBB) "
        "so no 6-digit comparison applies; pinned below by "
        "test_allowlisted_qt6ct_dark_equals_its_renderer"
    ),
}


def _dark_files() -> list[str]:
    files = [
        path
        for path in _tracked()
        if (ROOT / path).is_file()
        and not path.startswith(NOT_COLOUR_FILES)
        and DARK_NAME.search(Path(path).name)
    ]
    return sorted({*files, *DARK_ONLY_BY_CONTENT})


def _dark_tokens() -> set[str]:
    dark = json.loads(TOKENS.read_text(encoding="utf-8"))["modes"]["dark"]
    return {v.lower() for v in dark.values() if isinstance(v, str) and HEX.fullmatch(v)}


@pytest.fixture(scope="module")
def generated(tmp_path_factory: pytest.TempPathFactory) -> set[str]:
    return _generated_by_sync(tmp_path_factory.mktemp("dark-root"))


def test_the_dark_file_inventory_is_not_empty() -> None:
    files = _dark_files()
    assert len(files) > 40
    assert "DreamcoderAlacritty/.config/alacritty/dreamcoder-dark.toml" in files
    assert "DreamcoderZellij/.config/zellij/config-dark.kdl" in files


def test_allowlist_entries_are_justified_and_still_needed(generated: set[str]) -> None:
    dark = set(_dark_files())
    for path, reason in ALLOWLIST.items():
        assert reason.strip(), f"{path}: an allowlist entry needs a written reason"
        assert path in dark, f"{path}: allowlisted but not a tracked Dark file"
        assert path not in generated, f"{path}: generated by the sync, drop it from the allowlist"


@pytest.mark.parametrize("path", _dark_files())
def test_dark_file_is_generated_or_holds_only_dark_tokens(path: str, generated: set[str]) -> None:
    # A tracked symlink is as generated as the file it points at.
    if path in generated or _resolved(path) in generated:
        return
    if path in ALLOWLIST:
        return
    stale = _stale((ROOT / path).read_text(encoding="utf-8", errors="ignore"), _dark_tokens())
    assert not stale, f"{path}: not generated and carries non-Dark-token hex {stale}"


def test_apply_theme_mode_dark_branch_holds_only_dark_tokens() -> None:
    text = (ROOT / "scripts/apply-theme-mode.sh").read_text(encoding="utf-8")
    branch = re.search(r"^\s*dark\)\n(.*?)^\s*;;", text, re.MULTILINE | re.DOTALL)
    assert branch, "the Dark branch of the tmux palette case disappeared"
    stale = _stale(branch.group(1), _dark_tokens())
    assert not stale, f"scripts/apply-theme-mode.sh Dark branch carries stale hex {stale}"


def _dark_palette() -> dict[str, str]:
    return load_variants(VARIANTS, TOKENS)["dark"]


def test_allowlisted_dark_css_equals_its_generator() -> None:
    spec = importlib.util.spec_from_file_location(
        "generate_dark_css", ROOT / "scripts/generate-dark-css.py"
    )
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    path = ROOT / "DreamcoderThemes/dreamcoder/dreamcoder-dark.css"
    assert path.read_text(encoding="utf-8") == module.render_css(module.load_tokens())


def test_allowlisted_qt6ct_dark_equals_its_renderer() -> None:
    path = ROOT / "DreamcoderThemes/dreamcoder/qt6ct-dark.conf"
    assert path.read_text(encoding="utf-8") == qt6ct_content(_dark_palette())


@pytest.mark.parametrize("item", DARK_FILES, ids=lambda item: item.path)
def test_dark_file_on_disk_matches_its_renderer(item) -> None:
    assert (ROOT / item.path).read_text(encoding="utf-8") == (
        item.renderer(_dark_palette()).rstrip("\n") + "\n"
    ), f"{item.path} drifted from tokens.json; run the repo-only sync"


def test_the_sync_writes_every_dark_file_and_the_zellij_config(generated: set[str]) -> None:
    assert {item.path for item in DARK_FILES} <= generated
    assert ZELLIJ_DARK_CONFIG in generated


def test_dark_files_never_target_light_artifacts() -> None:
    assert all("light" not in item.path.lower() for item in DARK_FILES)
    assert "light" not in ZELLIJ_DARK_CONFIG.lower()


def test_zellij_dark_config_splice_keeps_everything_but_the_theme_block() -> None:
    dark = _dark_palette()
    current = (ROOT / ZELLIJ_DARK_CONFIG).read_text(encoding="utf-8")
    assert zellij_config_content(dark, "dreamcoder-dark", current) == current, "idempotent"
    foreign = current.replace(dark["accent"], "#123456")
    spliced = zellij_config_content(dark, "dreamcoder-dark", foreign)
    assert "#123456" not in spliced and dark["accent"] in spliced
    assert spliced.count("\nthemes {\n") == 1 and "dreamcoder-light" not in spliced
    assert spliced.startswith(current.split("\nthemes {\n")[0])
    assert spliced.endswith(
        '\ntheme "dreamcoder-dark"' + current.split('\ntheme "dreamcoder-dark"')[1]
    )


def test_zellij_dark_config_splice_rejects_a_config_without_a_themes_block() -> None:
    with pytest.raises(ValueError, match=r"themes \{ \}"):
        zellij_config_content(_dark_palette(), "dreamcoder-dark", 'theme "dreamcoder-dark"\n')


def test_sync_mode_files_dark_writes_every_file_and_skips_a_missing_zellij_config(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(sync, "ROOT", tmp_path)
    dark = _dark_palette()

    assert sync.sync_mode_files("dark", dark) == [True] * len(DARK_FILES)
    assert not (tmp_path / ZELLIJ_DARK_CONFIG).exists()
    for item in DARK_FILES:
        assert (tmp_path / item.path).read_text() == item.renderer(dark).rstrip("\n") + "\n"

    assert sync.sync_mode_files("dark", dark) == [False] * len(DARK_FILES), "second run is a no-op"


def test_sync_mode_files_dark_splices_an_existing_zellij_config(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(sync, "ROOT", tmp_path)
    config = tmp_path / ZELLIJ_DARK_CONFIG
    config.parent.mkdir(parents=True)
    config.write_text('themes {\n    old {\n        bg "#123456"\n    }\n}\n\ntheme "old"\n')

    changes = sync.sync_mode_files("dark", _dark_palette())

    assert changes[-1] is True
    text = config.read_text()
    assert "#123456" not in text and "dreamcoder-dark" in text
    assert text.endswith('\ntheme "old"\n')
    assert sync.sync_mode_files("dark", _dark_palette())[-1] is False


def test_tmux_ukiyo_dark_file_uses_exact_dark_tokens() -> None:
    out = tmux_ukiyo_content(_dark_palette())
    assert not _stale(out, _dark_tokens())
    assert out.count("@ukiyo-color-") == 11


def test_apply_theme_mode_dark_branch_sources_the_generated_ukiyo_file() -> None:
    text = (ROOT / "scripts/apply-theme-mode.sh").read_text(encoding="utf-8")
    branch = re.search(r"^\s*dark\)\n(.*?)^\s*;;", text, re.MULTILINE | re.DOTALL)
    assert branch
    assert "tmux-ukiyo-dark.conf" in branch.group(1)
    assert "@ukiyo-color-" not in branch.group(1), "colours come from the generated file"
    assert (ROOT / "DreamcoderThemes/dreamcoder/tmux-ukiyo-dark.conf").is_file()
